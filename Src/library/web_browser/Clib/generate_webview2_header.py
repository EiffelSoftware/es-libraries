#!/usr/bin/env python3
"""
Generate ../spec/include/eif_webview2_api.h: the subset of the WebView2 SDK header
(WebView2.h, from the NuGet package Microsoft.Web.WebView2, BSD-3-Clause licence)
used by eif_webview2.c, in C.

The COM interfaces are declared with their complete vtable layout: the methods
that are not used are kept as opaque slots (`void *name;`), so that the offsets
of the used methods are the ones of the SDK.

Usage: generate_webview2_header.py <path to WebView2.h> <SDK version>
"""

import re
import sys

# Interface -> used methods (None: all the methods, for the interfaces implemented by eif_webview2.c).
INTERFACES = {
	"ICoreWebView2Environment": ["CreateCoreWebView2Controller"],
	"ICoreWebView2Controller": [
		"put_IsVisible", "put_Bounds", "get_ZoomFactor", "put_ZoomFactor", "MoveFocus",
		"get_CoreWebView2", "Close", "NotifyParentWindowPositionChanged"],
	"ICoreWebView2": [
		"get_Settings", "get_Source", "Navigate", "NavigateToString",
		"add_NavigationStarting", "add_NavigationCompleted", "add_SourceChanged",
		"add_DocumentTitleChanged", "get_DocumentTitle", "add_WebMessageReceived",
		"ExecuteScript", "AddScriptToExecuteOnDocumentCreated", "Reload", "Stop",
		"get_CanGoBack", "get_CanGoForward", "GoBack", "GoForward", "add_NewWindowRequested"],
	"ICoreWebView2Settings": ["put_AreDevToolsEnabled", "put_IsWebMessageEnabled"],
	"ICoreWebView2Settings2": ["put_UserAgent"],
	"ICoreWebView2NavigationStartingEventArgs": ["get_Uri", "put_Cancel"],
	"ICoreWebView2NavigationCompletedEventArgs": ["get_IsSuccess", "get_WebErrorStatus"],
	"ICoreWebView2WebMessageReceivedEventArgs": ["TryGetWebMessageAsString"],
	"ICoreWebView2NewWindowRequestedEventArgs": ["get_Uri", "put_Handled"],
	"ICoreWebView2CreateCoreWebView2EnvironmentCompletedHandler": None,
	"ICoreWebView2CreateCoreWebView2ControllerCompletedHandler": None,
	"ICoreWebView2NavigationStartingEventHandler": None,
	"ICoreWebView2NavigationCompletedEventHandler": None,
	"ICoreWebView2SourceChangedEventHandler": None,
	"ICoreWebView2DocumentTitleChangedEventHandler": None,
	"ICoreWebView2WebMessageReceivedEventHandler": None,
	"ICoreWebView2NewWindowRequestedEventHandler": None,
}

# Types of the SDK used in the kept declarations, declared in the generated header.
FORWARD_TYPES = [
	"ICoreWebView2EnvironmentOptions", "ICoreWebView2SourceChangedEventArgs",
	"ICoreWebView2ExecuteScriptCompletedHandler",
	"ICoreWebView2AddScriptToExecuteOnDocumentCreatedCompletedHandler",
]

SAL = re.compile(r"\b_(?:COM_Outptr|Out|In|Inout|Outptr|In_opt|Out_opt|COM_Outptr_opt)_\b")


def vtable_methods(header, name):
	"""List of (method name, C declaration) of the vtable of the interface `name`."""
	m = re.search(r"typedef struct " + name + r"Vtbl\s*\{\s*BEGIN_INTERFACE(.*?)END_INTERFACE\s*\}\s*" + name + "Vtbl;", header, re.S)
	if not m:
		sys.exit("Vtable of " + name + " not found")
	body = m.group(1)
	parts = re.split(r"DECLSPEC_XFGVIRT\(\s*\w+\s*,\s*(\w+)\s*\)", body)
	result = []
	for i in range(1, len(parts), 2):
		decl = re.sub(r"/\*.*?\*/", "", parts[i + 1], flags=re.S)
		decl = SAL.sub("", decl)
		decl = re.sub(r"\s+", " ", decl).strip()
		result.append((parts[i], decl))
	return result


def iid(header, name):
	"""IID of the interface `name`, as a C initializer."""
	m = re.search(r'MIDL_INTERFACE\("([0-9a-fA-F-]+)"\)\s*' + name + r"\s*:", header)
	if not m:
		sys.exit("IID of " + name + " not found")
	g = m.group(1).split("-")
	b = g[3] + g[4]
	return "{0x%s, 0x%s, 0x%s, {%s}}" % (g[0], g[1], g[2], ", ".join("0x" + b[k:k + 2] for k in range(0, 16, 2)))


