#!/usr/bin/env python3
"""
generate_symbols_pixel.py

Generates library/core/style/symbols_pixel.e from Ratatui's pseudo-pixel tables
(ratatui/ratatui-core/src/symbols/pixel.rs: QUADRANTS, SEXTANTS, OCTANTS).

The tables are indexed by the pattern of a cell, with the pseudo-pixels in row-major order
(bit x + W * y), exactly as in Ratatui. The Eiffel class stores code points, so the source
stays ASCII (see tools/escape_non_ascii_literals.py).

Usage:
  python tools/generate_symbols_pixel.py                  # read ratatui/.../pixel.rs, write the class
  python tools/generate_symbols_pixel.py --source FILE    # read another copy of pixel.rs
  python tools/generate_symbols_pixel.py --stdout         # print the class instead of writing it
"""

import argparse
import datetime
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "ratatui", "ratatui-core", "src", "symbols", "pixel.rs")
OUTPUT = os.path.join(ROOT, "library", "core", "style", "symbols_pixel.e")

# (Rust constant, Eiffel table, expected size)
TABLES = [
    ("QUADRANTS", "Quadrant_table", 16),
    ("SEXTANTS", "Sextant_table", 64),
    ("OCTANTS", "Octant_table", 256),
]

CONST_RE = r"pub const {name}: \[char; (\d+)\] = \[(.*?)\];"
CHAR_RE = re.compile(r"'(.)'")


def parse(text, name, size):
    m = re.search(CONST_RE.format(name=name), text, re.S)
    if not m:
        raise SystemExit(f"{name} not found in pixel.rs")
    if int(m.group(1)) != size:
        raise SystemExit(f"{name} has {m.group(1)} entries, expected {size}")
    chars = CHAR_RE.findall(m.group(2))
    if len(chars) != size:
        raise SystemExit(f"{name}: parsed {len(chars)} characters, expected {size}")
    codes = [ord(c) for c in chars]
    # Pattern 0 is blank and the full pattern is a full block in every table
    assert codes[0] == 0x20 and codes[-1] == 0x2588, name
    return codes


def eiffel_table(name, rust_name, codes):
    lines = []
    for i in range(0, len(codes), 8):
        row = ", ".join(f"0x{c:04X}" for c in codes[i:i + 8])
        lines.append(f"{row}, -- {i}..{min(i + 7, len(codes) - 1)}")
    # No comma after the last value
    lines[-1] = lines[-1].replace(", --", " --", 1)
    body = "\n\t\t\t\t".join(lines)
    return (
        f"\t{name}: SPECIAL [NATURAL_32]\n"
        f"\t\t\t-- Code points of Ratatui `{rust_name}`, indexed by pattern ({len(codes)} entries).\n"
        f"\t\tonce\n"
        f"\t\t\tResult := ({{ARRAY [NATURAL_32]}} <<\n\t\t\t\t{body}\n\t\t\t>>).area\n"
        f"\t\tensure\n"
        f"\t\t\tinstance_free: class\n"
        f"\t\t\tcount: Result.count = {len(codes)}\n"
        f"\t\tend\n"
    )


TEMPLATE = '''note
	description: "[
		Pseudo-pixel characters: quadrants (2 x 2), sextants (2 x 3) and octants (2 x 4).
		Matches Ratatui `symbols::pixel`.

		A pattern holds one bit per pseudo-pixel in row-major order: bit x + W * y for the
		pseudo-pixel in column x and row y of a W x H cell. For a 2 x 4 octant:
		    | 0 1 |
		    | 2 3 |
		    | 4 5 |
		    | 6 7 |
		Pattern 0 is a space; the full pattern is a full block.

		GENERATED by tools/generate_symbols_pixel.py from Ratatui's
		ratatui-core/src/symbols/pixel.rs on {date}.
		Do not edit the tables by hand: change the generator and run it again.

		Font support: sextants are in "Symbols for Legacy Computing" (U+1FB00..U+1FB3B,
		Unicode 13.0). Most octants are in "Symbols for Legacy Computing Supplement"
		(U+1CD00..U+1CDE5 and U+1CEA0..U+1CEAB, Unicode 16.0); the rest are block elements
		or U+1FB82, U+1FB85, U+1FBE6, U+1FBE7. All of them are 1 column wide (UNICODE_WIDTH).
		A terminal font without these blocks shows replacement characters instead, as Ratatui
		warns: Windows Terminal with Cascadia Code 2404 or later has them, conhost does not.
		Quadrants are in "Block Elements" and work almost everywhere.

		An expanded class, like the other SYMBOLS_* classes: every feature is a class feature,
		called as `{SYMBOLS_PIXEL}.octant (p)`. EiffelStudio 26.09 has an incremental compilation
		bug: a melted build crashes at start when melted code is the first to use an expanded
		class. Freeze after such a change (see the V1 melt crash notes in
		review/p1_visualization_plan.md).
	]"
	author: "EiffelTUI Team"
	date: "$Date$"
	revision: "$Revision$"

expanded class
	SYMBOLS_PIXEL

feature -- Access

	quadrant (a_pattern: INTEGER): CHARACTER_32
			-- Quadrant character for the 2 x 2 `a_pattern`.
		require
			valid_pattern: a_pattern >= 0 and a_pattern < 16
		do
			Result := Quadrant_table [a_pattern].to_character_32
		ensure
			instance_free: class
		end

	sextant (a_pattern: INTEGER): CHARACTER_32
			-- Sextant character for the 2 x 3 `a_pattern`.
		require
			valid_pattern: a_pattern >= 0 and a_pattern < 64
		do
			Result := Sextant_table [a_pattern].to_character_32
		ensure
			instance_free: class
		end

	octant (a_pattern: INTEGER): CHARACTER_32
			-- Octant character for the 2 x 4 `a_pattern`.
		require
			valid_pattern: a_pattern >= 0 and a_pattern < 256
		do
			Result := Octant_table [a_pattern].to_character_32
		ensure
			instance_free: class
		end

feature {NONE} -- Generated tables

{tables}
end
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", default=SOURCE, help="path of Ratatui's symbols/pixel.rs")
    ap.add_argument("--stdout", action="store_true", help="print the class instead of writing it")
    args = ap.parse_args()

    with open(args.source, encoding="utf-8") as f:
        text = f.read()
    tables = "\n".join(eiffel_table(eiffel, rust, parse(text, rust, size)) for rust, eiffel, size in TABLES)
    out = TEMPLATE.replace("{date}", datetime.date.today().isoformat()).replace("{tables}", tables)
    if args.stdout:
        sys.stdout.write(out)
    else:
        with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(out)
        print(f"wrote {OUTPUT}: " + ", ".join(f"{rust} {size}" for rust, _, size in TABLES))


if __name__ == "__main__":
    main()
